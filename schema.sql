-- HALLHA starter database schema for Supabase.
-- Run this in Supabase SQL Editor after creating a project.
-- Auth users are managed by Supabase Auth; never store passwords yourself.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  avatar_url text,
  preferred_language text not null default 'ar',
  plan text not null default 'free' check (plan in ('free','premium')),
  created_at timestamptz not null default now()
);

create table if not exists public.favorites (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  tool_slug text not null,
  created_at timestamptz not null default now(),
  unique(user_id, tool_slug)
);

create table if not exists public.support_messages (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  email text,
  subject text not null,
  message text not null,
  status text not null default 'open' check (status in ('open','in_progress','closed')),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.favorites enable row level security;
alter table public.support_messages enable row level security;

create policy "Users can read own profile"
on public.profiles for select to authenticated
using (auth.uid() = id);

create policy "Users can update own profile"
on public.profiles for update to authenticated
using (auth.uid() = id)
with check (auth.uid() = id);

create policy "Users can add own profile"
on public.profiles for insert to authenticated
with check (auth.uid() = id);

create policy "Users manage own favorites"
on public.favorites for all to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

create policy "Users create support messages"
on public.support_messages for insert to authenticated
with check (auth.uid() = user_id);

create policy "Users read own support messages"
on public.support_messages for select to authenticated
using (auth.uid() = user_id);

-- Automatically create a profile when a new auth user signs up.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'display_name', ''));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();
